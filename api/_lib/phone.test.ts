import test from 'node:test';
import assert from 'node:assert/strict';
import { normalizePhone } from './phone.js';

/** [קלט, התוצאה המצופה — או null אם המספר אמור להיפסל, תיאור] */
const CASES: Array<[unknown, string | null, string]> = [
  ['0501234567', '972501234567', 'נייד רגיל'],
  ['050-123-4567', '972501234567', 'עם מקפים'],
  ['050 123 4567', '972501234567', 'עם רווחים'],
  ['+972501234567', '972501234567', 'פורמט בינלאומי'],
  ['+972-50-123-4567', '972501234567', 'בינלאומי עם מקפים'],
  ['00972501234567', '972501234567', 'קידומת 00'],
  ['972501234567', '972501234567', 'בינלאומי בלי פלוס'],
  ["'0501234567", '972501234567', 'גרש מוביל מעיצוב טקסט'],
  [501234567, '972501234567', 'מספר — האפס המוביל נבלע'],
  [' 054-9876543 ', '972549876543', 'רווחים בקצוות'],
  ['(052) 111-2233', '972521112233', 'סוגריים'],
  ['053.777.8899', '972537778899', 'נקודות'],
  ['0587654321', '972587654321', 'קידומת 058'],
  ['972 55 1234567', '972551234567', 'רווחים בבינלאומי'],
  // אמורים להיפסל
  ['', null, 'תא ריק'],
  ['   ', null, 'רווחים בלבד'],
  ['לא ידוע', null, 'טקסט בלי ספרות'],
  ['03-6543210', null, 'קו נייח — לא ווטסאפ'],
  ['0771234567', null, 'VOIP — לא נייד'],
  ['12345', null, 'קצר מדי'],
  [null, null, 'null'],
  [undefined, null, 'undefined'],
];

for (const [input, expected, description] of CASES) {
  test(`${description} — ${JSON.stringify(input)}`, () => {
    const result = normalizePhone(input);
    const got = result.ok ? result.phone : null;
    assert.equal(got, expected);
    // מספר שנפסל חייב להסביר למה — ההודעה מוצגת למשתמש כמו שהיא.
    if (!result.ok) assert.ok(result.reason.length > 0, 'חסרה סיבת פסילה');
  });
}
